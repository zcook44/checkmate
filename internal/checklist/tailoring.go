package checklist

import (
	"fmt"
	"sort"
	"strings"
)

// TailoringEntry represents one rule in a tailoring file.
type TailoringEntry struct {
	RuleName string // SSG rule name (will be placeholder)
	StigID   string // V-number
	SvID     string // SV-number_rule
	Status   string
	Comment  string
}

// TailoringFile represents a complete tailoring YAML structure.
type TailoringFile struct {
	Benchmark string
	Release   string
	Entries   []TailoringEntry
}

// AnalyzeTailoring examines loaded CKLBs and identifies rules where all hosts
// have the same status and comment, making them candidates for tailoring.
func AnalyzeTailoring(files []File, onlyNonDefault bool) []TailoringFile {
	// Group by benchmark + release
	type key struct {
		benchmark, release string
	}
	type ruleKey struct {
		id, ruleID string
	}
	type pattern struct {
		status  string
		comment string
		count   int
	}
	
	benchmarks := make(map[key]map[ruleKey]pattern)
	
	// Collect all status/comment combinations for each rule across hosts
	for _, f := range files {
		for _, r := range f.Rules {
			k := key{r.Benchmark, r.Release}
			if benchmarks[k] == nil {
				benchmarks[k] = make(map[ruleKey]pattern)
			}
			rk := ruleKey{r.ID, r.RuleID}
			p := benchmarks[k][rk]
			// Check if this is the first occurrence or if it matches existing pattern
			if p.count == 0 {
				p.status = r.Status
				p.comment = r.Comment
				p.count = 1
			} else if p.status == r.Status && p.comment == r.Comment {
				p.count++
			} else {
				// Inconsistent - mark as invalid by setting count to -1
				p.count = -1
			}
			benchmarks[k][rk] = p
		}
	}
	
	// Count total hosts per benchmark
	hostCounts := make(map[key]int)
	for _, f := range files {
		if len(f.Rules) > 0 {
			k := key{f.Rules[0].Benchmark, f.Rules[0].Release}
			hostCounts[k]++
		}
	}
	
	// Build tailoring files for each benchmark
	var results []TailoringFile
	for bk, rules := range benchmarks {
		tf := TailoringFile{
			Benchmark: bk.benchmark,
			Release:   bk.release,
		}
		
		for rk, p := range rules {
			// Only include if all hosts have the same status/comment
			if p.count != hostCounts[bk] || p.count <= 0 {
				continue
			}
			
			// Optionally filter out "not_reviewed" with empty/default comments
			if onlyNonDefault {
				if p.status == "not_reviewed" && 
					(strings.TrimSpace(p.comment) == "" || 
					 strings.Contains(p.comment, "NOT REVIEWED")) {
					continue
				}
			}
			
			entry := TailoringEntry{
				RuleName: "PLACEHOLDER",  // Will need manual completion
				StigID:   rk.id,
				SvID:     rk.ruleID,
				Status:   p.status,
				Comment:  p.comment,
			}
			tf.Entries = append(tf.Entries, entry)
		}
		
		// Sort entries by STIG ID for consistency
		sort.Slice(tf.Entries, func(i, j int) bool {
			return tf.Entries[i].StigID < tf.Entries[j].StigID
		})
		
		if len(tf.Entries) > 0 {
			results = append(results, tf)
		}
	}
	
	// Sort by benchmark name
	sort.Slice(results, func(i, j int) bool {
		return results[i].Benchmark < results[j].Benchmark
	})
	
	return results
}

// FormatTailoringYAML converts a TailoringFile to YAML format.
func FormatTailoringYAML(tf TailoringFile) string {
	var b strings.Builder
	
	// Header comment
	fmt.Fprintf(&b, "# %s tailoring\n", tf.Benchmark)
	fmt.Fprintf(&b, "# %s\n", tf.Release)
	fmt.Fprintf(&b, "#\n")
	fmt.Fprintf(&b, "# IMPORTANT: This file was generated by checkmate --export-tailoring.\n")
	fmt.Fprintf(&b, "# The 'rule_name' fields are placeholders and must be filled in manually.\n")
	fmt.Fprintf(&b, "# rule_name is the SSG (SCAP Security Guide) remediation rule name.\n")
	fmt.Fprintf(&b, "#\n")
	fmt.Fprintf(&b, "# To find rule_name values:\n")
	fmt.Fprintf(&b, "# 1. Check the burden-of-proof/docket converter documentation\n")
	fmt.Fprintf(&b, "# 2. Reference existing tailoring files for similar rules\n")
	fmt.Fprintf(&b, "# 3. Consult SSG content for your OS version\n")
	fmt.Fprintf(&b, "#\n")
	fmt.Fprintf(&b, "# status: auto keeps the scan's candidate status; set an explicit CKLB status\n")
	fmt.Fprintf(&b, "# only after reviewing the control and updating the administrator comment.\n")
	fmt.Fprintf(&b, "# This file applies to EVERY %s host converted with this library.\n", tf.Benchmark)
	fmt.Fprintf(&b, "rules:\n")
	
	for _, e := range tf.Entries {
		// Map CKLB status to tailoring status
		// CKLB uses: open, not_reviewed, not_a_finding, not_applicable
		// Tailoring can use: auto (keep scan result), or explicit statuses
		tailoringStatus := "auto"
		if e.Status != "not_reviewed" {
			tailoringStatus = e.Status
		}
		
		fmt.Fprintf(&b, "  - rule_name: %s  # TODO: Fill in SSG rule name\n", e.RuleName)
		fmt.Fprintf(&b, "    stig_id: %s\n", e.StigID)
		fmt.Fprintf(&b, "    sv_id: %s\n", e.SvID)
		fmt.Fprintf(&b, "    status: %s\n", tailoringStatus)
		
		// Format comment with proper YAML escaping
		comment := strings.ReplaceAll(e.Comment, "\"", "\\\"")
		fmt.Fprintf(&b, "    comment: \"%s\"\n", comment)
	}
	
	return b.String()
}
